/**
 * Схеманы бөлек құрады: `npm run db:migrate`.
 *
 * Тұрақты серверде мұны `server/index.js` іске қосылу кезінде өзі істейді.
 * Vercel-де ондай «іске қосылу» сәті жоқ — функция әр сұраныста қайта
 * оянады, ал әр оянған сайын DDL жіберу артық жүк әрі бір мезгілде бірнеше
 * функция бірдей `CREATE TABLE` жіберіп қалуы мүмкін. Сондықтан схема
 * деплойдың build қадамында, бір рет жаңарады (`vercel.json` → buildCommand).
 *
 * Сұраныстар мұны күтпейді: build сәтті бітпейінше жаңа нұсқа тірі
 * трафикке шықпайды.
 */

// `server/db.js` DATABASE_URL жоқ болса импорт кезінде-ақ құлайды. Preview
// деплойға немесе бөгде ортаға айнымалы қойылмаған болуы мүмкін — ондайда
// build-ты түсінікті емес қатемен құлатқаннан гөрі, себебін жазып шыққан
// дұрыс. Қор жоқ болса қолданба қалай болса да іске қосылмайды.
if (!process.env.DATABASE_URL) {
  console.warn(
    'DATABASE_URL қойылмаған — схема жаңартылмады. Хостингтің панелінде ' +
      'айнымалыны қосып, деплойды қайтала (немесе жергілікті жерде ' +
      '`npm run db:migrate` орында).',
  )
  process.exit(0)
}

const { migrate, closePool } = await import('../server/db.js')

try {
  await migrate()
  console.log('Схема дайын.')
} catch (error) {
  console.error('Схеманы жаңарту сәтсіз:', error)
  process.exitCode = 1
} finally {
  await closePool().catch(() => {})
}
